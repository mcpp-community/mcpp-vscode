#!/usr/bin/env node
/**
 * `data/config-registry.json` -> `docs/settings.md`.
 *
 * The user documentation of settings is generated so it cannot drift from the
 * manifest: `tools/check-config.mjs` already holds the registry to
 * `package.json`, and this holds the docs to the registry. Make targets run
 * `npm run gen:docs` then `git diff --exit-code`.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const registry = JSON.parse(fs.readFileSync(path.join(root, "data", "config-registry.json"), "utf8"));
// The Chinese descriptions already exist for the Settings UI (`package.nls.zh-cn.json`);
// reusing them keeps one source per language instead of a third copy in these docs.
const zhNls = JSON.parse(fs.readFileSync(path.join(root, "package.nls.zh-cn.json"), "utf8"));

const APPLIES = {
  immediate: "Takes effect immediately",
  "next-build": "Takes effect on the next build/run/test",
  "next-clean": "Takes effect on the next clean",
  "view-reload": "Takes effect after the window reloads",
};

const SCOPE = {
  resource: "per folder",
  window: "per window",
};

const groups = [...registry.groups].sort((a, b) => a.order - b.order);
const lines = [];
lines.push("# Settings");
lines.push("");
lines.push("<!-- Generated by `npm run gen:docs` from `data/config-registry.json`. Do not edit by hand. -->");
lines.push("");
lines.push(`${registry.settings.length} settings, in ${groups.length} groups. All of them are read by the`);
lines.push("**mcpp** extension only. `mcppls.*` belongs to the C++ Modules extension and is never");
lines.push("written by this one; the configuration panel says so on every screen.");
lines.push("");
lines.push("| | |");
lines.push("|---|---|");
lines.push("| Panel | **mcpp: Open Settings Panel** (`mcpp.openSettings`) |");
lines.push("| Native UI | Settings → Extensions → mcpp, or `@ext:mcpp-community.mcpp-vscode` |");
lines.push("| Defaults | Every default is deliberately quiet: nothing here changes behaviour until you ask |");
lines.push("");

for (const group of groups) {
  const rows = registry.settings
    .filter((entry) => entry.group === group.id)
    .sort((a, b) => a.order - b.order);
  if (rows.length === 0) continue;
  lines.push(`## ${group.title}`);
  lines.push("");
  for (const entry of rows) {
    const badges = [];
    if (entry.deprecated) badges.push("**deprecated**");
    if (entry.tier === "advanced") badges.push("advanced");
    lines.push(`### \`${entry.key}\`${badges.length > 0 ? ` — ${badges.join(", ")}` : ""}`);
    lines.push("");
    lines.push(entry.description);
    const zh = zhNls[`${entry.key}.description`];
    if (typeof zh === "string" && zh.length > 0) {
      lines.push("");
      lines.push(zh);
    }
    lines.push("");
    lines.push("| | |");
    lines.push("|---|---|");
    lines.push(`| Type | \`${entry.type}\`${entry.enum ? `: ${entry.enum.map((value) => `\`${value}\``).join(" \\| ")}` : ""} |`);
    lines.push(`| Default | \`${JSON.stringify(entry.default)}\` |`);
    if (entry.minimum !== undefined || entry.maximum !== undefined) {
      lines.push(`| Range | ${entry.minimum ?? "−∞"} … ${entry.maximum ?? "∞"} |`);
    }
    lines.push(`| Scope | ${SCOPE[entry.scope] ?? entry.scope} |`);
    lines.push(`| Applies | ${APPLIES[entry.applies] ?? entry.applies} |`);
    lines.push(`| Since | ${entry.since} |`);
    if (entry.aliases?.length) {
      lines.push(`| Old name | ${entry.aliases.map((alias) => `\`${alias}\``).join(", ")} (still read) |`);
    }
    if (entry.deprecationMessage) {
      lines.push(`| Deprecated | ${entry.deprecationMessage} |`);
    }
    lines.push("");
  }
}

lines.push("## Language");
lines.push("");
lines.push("`mcpp.ui.language` overrides the language of **runtime messages and this extension's");
lines.push("panels**. The command palette and the Settings UI always follow the editor's own");
lines.push("language: VS Code resolves `package.nls.*` once at startup, so a manual override");
lines.push("cannot reach them. `auto` (the default) follows the editor everywhere.");
lines.push("");

const target = path.join(root, "docs", "settings.md");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, `${lines.join("\n")}`);
console.log(`generate-settings-docs: wrote ${path.relative(root, target)} (${registry.settings.length} settings)`);
