#!/usr/bin/env node
/** Real Chromium + shipped Mermaid and canvas. No VS Code installation is needed. */
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
const require = createRequire(import.meta.url);
const {chromium} = require('playwright');
const {graphPanelHtml} = require('../dist/src/graphs/panelHtml.js');
const {visibleGraph, mermaidGraph, groupedGraph, INITIAL_GRAPH_BUDGET} = require('../dist/src/graphs/model.js');
const {decodeGraphExport} = require('../dist/src/graphs/export.js');
const artifacts = path.resolve('.dev-profile/graph-ui-artifacts');
await fs.mkdir(artifacts, {recursive:true});
const browser = await chromium.launch({headless:true, ...(process.env.MCPP_UI_CHROMIUM ? {executablePath:process.env.MCPP_UI_CHROMIUM} : {}), args:['--no-sandbox']});
const checks=[];
try {
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[]; page.on('pageerror', error=>errors.push(error.message));
  let html = graphPanelHtml({nonce:'graph-test',cspSource:'',styleUri:''},'', '');
  html = html.replace(/<meta http-equiv="Content-Security-Policy"[^>]*>/,'').replace(/<link[^>]*>/g,'').replace(/<script nonce="graph-test" src=""><\/script>/g,'');
  await page.setContent(html);
  await page.addStyleTag({content:await fs.readFile('media/dependencyGraph.css','utf8')});
  await page.addStyleTag({content:':root{--vscode-foreground:#ddd;--vscode-descriptionForeground:#aaa;--vscode-editor-background:#202020;--vscode-charts-blue:#3498db;--vscode-charts-purple:#a98bdd;--vscode-charts-green:#4d8;--vscode-focusBorder:#fc8;--vscode-font-family:system-ui}body{background:#202020}'});
  await page.evaluate(()=>{
    window.messages=[]; window.acquireVsCodeApi=()=>({postMessage: message=>window.messages.push(message)});
    window.renders=[];
  });
  await page.addScriptTag({path:path.resolve('dist/vendor/mermaid.js')});
  await page.evaluate(()=>{const render=mermaid.render; mermaid.render=async(...args)=>{const start=performance.now();const result=await render(...args);window.renders.push(performance.now()-start);return result;};});
  await page.addScriptTag({path:path.resolve('media/graph.js')});
  const node=id=>({id,label:id,lines:['source','模块'],kind:'project'});
  const graph={nodes:['main','a','b','c','d','e','parent','grandparent','sibling'].map(node),edges:[{from:'main',to:'a'},{from:'a',to:'b'},{from:'b',to:'c'},{from:'c',to:'d'},{from:'d',to:'e'},{from:'parent',to:'main'},{from:'grandparent',to:'parent'},{from:'parent',to:'sibling'}],roots:['grandparent'],groups:[{id:'@group/main',label:'Main',nodes:['main']}]};
  let state={depth:3,upstreamDepth:2,expanded:new Set(),collapsed:new Set(),localDepth:new Map(),focus:'main'};
  const emit=message=>page.evaluate(message=>dispatchEvent(new MessageEvent('message',{data:message})),message);
  await emit({type:'snapshot',viewKey:'modules:fixture',search:graph.nodes.map(({id,label})=>({id,label})),groups:graph.groups});
  const message=()=>{
    const visible=visibleGraph(graph,state,INITIAL_GRAPH_BUDGET);
    return {type:'graph',viewKey:'modules:fixture',mode:'modules',name:'fixture',depth:String(state.depth),upstreamDepth:String(state.upstreamDepth), ...mermaidGraph(visible),
      nodes:visible.nodes.map(node=>({id:node.id,label:node.label,hidden:visible.hidden.get(node.id)||0})),focus:state.focus,selected:'main',limited:visible.limited,truncated:false};
  };
  await emit(message()); await page.waitForSelector('.node[data-node-key="c"]');
  assert.equal(await page.locator('.node[data-node-key="grandparent"]').count(),1);
  assert.equal(await page.locator('.node[data-node-key="sibling"]').count(),0);
  checks.push('two parent hops exclude sibling dependencies');
  assert.equal(await page.locator('#graph-depth').isVisible(),false);
  assert.equal(await page.locator('[data-export="svg"]').isVisible(),false);
  assert.equal(await page.locator('[data-export="png"]').isVisible(),false);
  await page.locator('#graph-export summary').click();
  assert.equal(await page.locator('[data-action="copy"]').isVisible(),true);
  await page.locator('[data-action="copy"]').click();
  assert.equal(await page.locator('[data-export="svg"]').isVisible(),false);
  await page.locator('#graph-view-menu summary').click();
  const depths = await page.locator('#graph-view-menu select').evaluateAll(items => items.map(item => { const r=item.getBoundingClientRect(); return {left:r.left,width:r.width,height:r.height}; }));
  assert.deepEqual(depths[0],depths[1]);
  const header = await page.locator('.graph-header [data-action=refresh],#graph-export>summary').evaluateAll(items=>items.map(item=>{const r=item.getBoundingClientRect();return {top:r.top,height:r.height,color:getComputedStyle(item).color};}));
  assert.equal(header[0].top,header[1].top); assert.equal(header[0].height,header[1].height); assert.notEqual(header[0].color,header[1].color);
  await page.screenshot({path:path.join(artifacts,'view-options.png')});
  await page.locator('#graph-upstream').selectOption('3');
  assert.equal(await page.evaluate(()=>messages.filter(m=>m.action==='upstreamDepth').at(-1).depth),'3');
  assert.equal(await page.locator('#graph-depth').isVisible(),false);
  await page.locator('#graph-view-menu summary').click(); await page.keyboard.press('Escape');
  assert.equal(await page.locator('#graph-view-menu summary').evaluate(e=>document.activeElement===e),true);
  checks.push('compact menus retain exports, copy and depths; Escape closes and restores keyboard focus');
  const a=page.locator('.node[data-node-key="a"]'); await a.click();
  assert.equal(await page.evaluate(()=>messages.filter(m=>m.action==='open').length),0);
  await page.locator('[data-action="focus"]').click();
  assert.equal(await page.evaluate(()=>messages.filter(m=>m.action==='focus').at(-1).id),'a');
  await a.dblclick(); assert.equal(await page.evaluate(()=>messages.filter(m=>m.action==='open').length),1);
  checks.push('single click selects, double click opens once, Focus targets selection');
  await a.click({button:'right'});
  assert.equal(await page.locator('#graph-node-menu').count(),0);
  await page.locator('[data-context-action="expand"]').click();
  assert.equal(await page.evaluate(()=>messages.filter(m=>m.action==='expand').at(-1).id),'a');
  await a.focus(); await page.keyboard.press('Shift+F10');
  assert.equal(await page.locator('#graph-node-context').isVisible(),true);
  await page.keyboard.press('ArrowDown');
  assert.equal(await page.locator('[data-context-action="locate"]').evaluate(e=>document.activeElement===e),true);
  await page.screenshot({path:path.join(artifacts,'node-context.png')});
  await page.keyboard.press('Escape');
  assert.equal(await a.evaluate(e=>document.activeElement===e),true);
  checks.push('node context menu targets clicked node, supports keyboard navigation and restores focus; controls align and use theme colors');
  const renders=await page.evaluate(()=>renders.length);
  await page.locator('[data-action="locate"]').click();
  await page.locator('[data-zoom="+"]').click();
  await emit(message()); await page.waitForTimeout(80);
  assert.equal(await page.evaluate(()=>renders.length),renders);
  checks.push('selection, camera and identical graph updates do not relayout');
  state.localDepth.set('a',3); await emit(message()); await page.waitForSelector('.node[data-node-key="d"]');
  state.localDepth.set('a',4); await emit(message()); await page.waitForSelector('.node[data-node-key="e"]');
  state.collapsed.add('b'); await emit(message()); await page.waitForFunction(()=>!document.querySelector('.node[data-node-key="c"]'));
  assert.equal(await page.locator('.node[data-node-key="main"]').count(),1);
  checks.push('successive local expansion and branch collapse');
  await page.locator('#graph-search').fill('e'); await page.locator('#graph-search').press('Enter');
  assert.equal(await page.locator('#graph-search-focus').isVisible(),true);
  await page.locator('#graph-search-focus').click(); assert.equal(await page.evaluate(()=>messages.filter(m=>m.action==='search').at(-1).id),'e');
  checks.push('hidden search result offers an explicit focus action');
  for(const theme of ['vscode-light','vscode-dark']) {
    await page.evaluate(theme=>document.body.className=theme,theme); await page.waitForTimeout(150);
    await page.locator('#graph-export summary').click();
    await page.locator('[data-export="svg"]').click();
    await page.waitForFunction(()=>messages.some(m=>m.action==='export'&&m.format==='svg'));
    const svg=await page.evaluate(()=>messages.filter(m=>m.action==='export'&&m.format==='svg').at(-1).data);
    await fs.writeFile(path.join(artifacts,`${theme}.svg`),svg);
    decodeGraphExport('svg',svg); assert.ok(svg.includes('模块')); assert.ok(!svg.includes('translate(') || svg.includes('<g'));
    await fs.writeFile(path.join(artifacts,`${theme}.svg`),svg);
    await page.evaluate(()=>messages=messages.filter(m=>m.action!=='export'));
    await page.locator('#graph-export summary').click();
    await page.locator('[data-export="png"]').click();
    await page.waitForFunction(()=>messages.some(m=>m.action==='export'&&m.format==='png'));
    const png=decodeGraphExport('png',await page.evaluate(()=>messages.find(m=>m.action==='export'&&m.format==='png').data));
    await fs.writeFile(path.join(artifacts,`${theme}.png`),png.bytes);
    const offline=await browser.newPage(); await offline.goto('file://'+path.join(artifacts,`${theme}.svg`));
    assert.equal(await offline.locator('svg').count(),1); assert.ok((await offline.locator('text').allTextContents()).join('').includes('模块')); await offline.close();
    await page.evaluate(()=>messages=messages.filter(m=>m.action!=='export'));
  }
  checks.push('light/dark offline SVG and PNG preserve Unicode and validate');
  const beforeSwitch=await page.evaluate(()=>renders.length);
  const other={...message(),viewKey:'modules:fixture2',nodes:message().nodes.map(node=>({...node,id:'other/'+node.id})),focus:'other/main',selected:'other/main'};
  await emit({type:'snapshot',viewKey:other.viewKey,search:other.nodes,groups:[]});await emit(other);
  await page.waitForSelector('.node[data-node-key="other/main"]');
  assert.equal(await page.locator('#graph-search-focus').isVisible(),false);
  await page.locator('.node[data-node-key="other/main"]').click();
  assert.equal(await page.evaluate(()=>messages.filter(m=>m.action==='select').at(-1).id),'other/main');
  assert.equal(await page.evaluate(()=>renders.length),beforeSwitch);
  checks.push('identical drawings in different projects reuse layout but rebind node identities');
  const ids=Array.from({length:151},(_,i)=>`test${i}`);
  const wide={nodes:[node('main'),node('dep'),...ids.map(node)],edges:[{from:'main',to:'dep'},...ids.map(from=>({from,to:'dep'}))],roots:['main',...ids],groups:[{id:'@group/main',label:'Main',nodes:['main']},{id:'@group/tests',label:'Tests',nodes:ids}]};
  const grouped=visibleGraph(groupedGraph(wide,'@group/tests',20),{depth:1,upstreamDepth:2,expanded:new Set(),collapsed:new Set()},INITIAL_GRAPH_BUDGET);
  assert.equal(grouped.edges.filter(edge=>edge.containment).length,20); assert.ok(grouped.edges.some(edge=>edge.to==='dep'));
  checks.push('151 test entries page without starving dependencies');
  await emit({type:'snapshot',viewKey:'modules:groups',search:wide.nodes,groups:wide.groups});
  await emit({type:'graph',viewKey:'modules:groups',mode:'modules',name:'test entries',depth:'1',upstreamDepth:'2',group:'@group/tests',offset:20,
    ...mermaidGraph(grouped),nodes:grouped.nodes.map(node=>({id:node.id,label:node.label,virtual:!!node.virtual,hidden:grouped.hidden.get(node.id)||0})),selected:'@group/tests'});
  await page.waitForSelector('.node[data-node-key="@group/tests"]');
  await page.locator('.node[data-node-key="@group/tests"]').click({button:'right'});
  assert.equal(await page.locator('[data-context-action="open"]').isDisabled(),true);
  assert.equal(await page.locator('[data-context-action="expandParents"]').isDisabled(),true);
  assert.equal(await page.locator('[data-context-action="expand"]').isDisabled(),false);
  await page.keyboard.press('Escape');
  checks.push('virtual entry groups offer applicable node actions and correct paging');

  assert.deepEqual(errors,[]);
  await page.screenshot({path:path.join(artifacts,'canvas.png')});
  const report={checks,renderMs:await page.evaluate(()=>renders)};
  await fs.writeFile(path.join(artifacts,'results.json'),JSON.stringify(report,null,2)); console.log(JSON.stringify(report,null,2));
} finally {await browser.close();}
